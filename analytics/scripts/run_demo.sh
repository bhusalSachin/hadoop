#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"

echo "Checking available tools..."
if command -v hdfs >/dev/null 2>&1; then
  echo "Step 1: Uploading processed CSV files to HDFS"
  ./analytics/scripts/upload_to_hdfs.sh
else
  echo "HDFS CLI not found in PATH. This environment is using the local processed CSV fallback for demo execution."
fi

SPARK_CMD="spark-submit"
if ! command -v "$SPARK_CMD" >/dev/null 2>&1; then
  SPARK_CMD="/home/void/.cache/uv/archive-v0/zljKGyHmP6hDbxW3PE8Qg/pyspark/bin/spark-submit"
fi

if [[ ! -x "$SPARK_CMD" ]]; then
  echo "Spark submit binary not found. Please install PySpark or configure your local Spark installation."
  exit 1
fi

echo "Step 2: Running Spark analytics job"
if command -v hdfs >/dev/null 2>&1; then
  "$SPARK_CMD" --master local[*] --conf spark.hadoop.fs.defaultFS=hdfs://localhost:9000 ./analytics/spark/nepse_analytics.py
else
  "$SPARK_CMD" --master local[*] ./analytics/spark/nepse_analytics.py
fi

if command -v hdfs >/dev/null 2>&1; then
  echo "Step 3: Downloading HDFS results to local output folder"
  ./analytics/scripts/download_results.sh
else
  echo "HDFS is not installed; using the local output directory generated by the Spark job."
fi

echo "Step 4: Rendering simple charts"
python3 ./analytics/scripts/visualize_charts.py

echo "Demo complete. Results are available under ./analytics/output and, when HDFS is installed, under /nepse/analytics."
